// Copies contract ABIs from Foundry's build output into app/src/abi.ts, typed `as const` for viem.
// Run after `forge build`: node app/scripts/abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const contracts = [
  "CreditManager", "CreditLine", "CreditPool", "TrancheVault", "IdentityRegistry", "RiskCurator", "RiskLens",
  "ScoreOracle", "TradeGuard", "CircuitBreaker", "HistoryLinkRegistry", "IExchange",
];
let out = "// Generated by app/scripts/abi.mjs from Foundry's out/ directory. Do not edit.\n\n";
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"));
  const ident = name[0].toLowerCase() + name.slice(1) + "Abi";
  out += `export const ${ident} = ${JSON.stringify(abi)} as const;\n\n`;
}
writeFileSync(join(root, "app", "src", "abi.ts"), out);
console.log(`wrote ${contracts.length} ABIs to app/src/abi.ts`);
